export const HEXAGRAMS = rows.map(([name, upper, lower, shortMeaning], i) => {
  const binary = TRIGRAMS[lower] + TRIGRAMS[upper];
  return {
    number: i + 1,
    name,
    symbol: String.fromCodePoint(0x4dc0 + i),
    upper,
    lower,
    binary,
    shortMeaning,
    judgmentReference: `《周易》上、下經，第 ${i + 1} 卦〈${name}〉卦辭與爻辭`,
    lineIdentifiers: [...binary].map((b, j) =>
      j === 0
        ? `初${b === "1" ? "九" : "六"}`
        : j === 5
          ? `上${b === "1" ? "九" : "六"}`
          : `${b === "1" ? "九" : "六"}${["", "二", "三", "四", "五"][j]}`,
    ),
  };
});
export type Hexagram = (typeof HEXAGRAMS)[number];
