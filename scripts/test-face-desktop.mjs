import { _electron as electron, expect } from '@playwright/test';
import { readFile, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
const root = process.cwd();
const fixture = process.env.MINGLI_FACE_FIXTURE;
if (!fixture) throw new Error('Set MINGLI_FACE_FIXTURE to a licensed test portrait; no private photo is required.');
const report = { date: new Date().toISOString(), checks: [], errors: [] };
const env = Object.fromEntries(['PATH', 'HOME', 'TMPDIR', 'LANG'].filter(k => process.env[k]).map(k => [k, process.env[k]]));
const app = await electron.launch({ args: [path.join(root, 'work/desktop-app')], env: { ...env, MINGLI_TEST_DATA: path.join(root, 'work/face-validation-data') } });
try {
  const page = await app.firstWindow(); page.on('pageerror', error => report.errors.push(error.message));
  const requests = []; page.on('request', request => requests.push(request.url()));
  await page.getByRole('navigation', { name: '主要導覽' }).getByRole('link', { name: '面相觀察', exact: true }).click();
  await expect(page.getByRole('heading', { name: '面相文化觀察', exact: true })).toBeVisible();
  await page.getByLabel('選擇你有權使用的照片', { exact: true }).setInputFiles({ name: 'bad.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('not a photograph') });
  await expect(page.locator('.notice.error')).toContainText('照片格式或尺寸不支援'); report.checks.push('invalid image rejected');
  await page.getByLabel('選擇你有權使用的照片', { exact: true }).setInputFiles(fixture);
  await expect(page.getByRole('heading', { name: '這張照片上的比例', exact: true })).toBeVisible({ timeout: 30000 });
  await expect(page.locator('svg.face-preview polyline')).toHaveCount(8);
  expect(await page.locator('svg.face-preview circle').count()).toBeGreaterThan(50);
  const storage = await page.evaluate(() => JSON.stringify({ ...localStorage })); expect(storage).not.toContain('data:image');
  await expect(page.getByLabel('儲存時附上照片（預設不勾選）')).not.toBeChecked();
  report.checks.push('actual native landmarks + overlay + measurements + no automatic storage');
  const destination = path.join(root, 'work/face-report-no-photo.json');
  await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, destination);
  await page.getByRole('button', { name: '儲存觀察紀錄', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('檔案不含照片');
  expect(JSON.parse(await readFile(destination, 'utf8'))).not.toHaveProperty('photo');
  expect((await stat(destination)).mode & 0o777).toBe(0o600);
  await page.getByLabel('儲存時附上照片（預設不勾選）').check();
  await page.getByRole('button', { name: '儲存觀察紀錄', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('觀察紀錄與照片已儲存');
  expect(JSON.parse(await readFile(destination, 'utf8')).photo).toMatch(/^data:image\/jpeg;base64,/);
  report.checks.push('photo-free export default + explicit photo export + private file permissions');
  await page.screenshot({ path: 'outputs/face-desktop-preview.png', fullPage: true });
  await page.getByRole('button', { name: '移除本頁照片', exact: true }).click();
  await expect(page.locator('svg.face-preview')).toHaveCount(0);
  await page.getByLabel('選擇你有權使用的照片', { exact: true }).setInputFiles(fixture);
  await expect(page.locator('svg.face-preview')).toBeVisible({ timeout: 30000 });
  await page.getByRole('navigation', { name: '主要導覽' }).getByRole('link', { name: '首頁', exact: true }).click();
  await page.getByRole('navigation', { name: '主要導覽' }).getByRole('link', { name: '面相觀察', exact: true }).click();
  await expect(page.locator('svg.face-preview')).toHaveCount(0);
  report.checks.push('clear photo + no retained photo after leaving page');
  expect(requests.filter(url => /^https?:/.test(url))).toEqual([]);
  report.checks.push('no HTTP requests during photo processing');
  expect(report.errors).toEqual([]); report.passed = true;
  console.log(JSON.stringify(report));
} catch (error) { report.passed = false; report.failure = error.message; console.error(report.failure); process.exitCode = 1; }
finally { await app.close(); await writeFile('outputs/face-desktop-validation.json', JSON.stringify(report, null, 2)); }
